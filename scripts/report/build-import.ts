/**
 * Step 2 of the yearly report import: turns the private JSON + media manifest into
 *   private/import-<year>.sql       one batch: wipe the report content tables, insert it again
 *   private/r2-upload-list.txt      local file → R2 key (→ md5), one per line
 *
 *   bun scripts/report/build-import.ts [--year 2025-2026]
 *
 * See lib.ts for which tables are wiped and which are never touched. Logs contain counts only.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { buildImport } from "./lib";
import { manifestSchema, reportSchema } from "./types";

const { values: args } = parseArgs({
  args: Bun.argv.slice(2),
  options: { year: { type: "string", default: "2025-2026" } },
});
const year = args.year!;
const report = reportSchema.parse(JSON.parse(readFileSync(`private/report-${year}.json`, "utf8")));
const manifest = manifestSchema.parse(
  JSON.parse(readFileSync("private/report-media/manifest.json", "utf8")),
);

const { statements, uploads } = buildImport(report, manifest);
const sql = [
  `-- Generated by scripts/report/build-import.ts from private/report-${year}.json. Do not edit.`,
  `-- Wipes and re-inserts the ${year} report content; users, applications, enrollment rounds,`,
  `-- sign-ups, logged hours, audit log, rate limits and config settings are never touched.`,
  ...statements,
].join("\n");

// Phone numbers must never reach the SQL (8 digits; timestamps are 13).
if (/(?<![\d.])\d{8}(?![\d.])/.test(sql)) throw new Error("SQL looks like it holds a phone number");

writeFileSync(`private/import-${year}.sql`, sql + "\n");
writeFileSync(
  "private/r2-upload-list.txt",
  uploads.map((u) => `${u.file}\t${u.key}\t${u.md5}`).join("\n") + "\n",
);
console.log(
  `✅ private/import-${year}.sql: ${statements.length} statements · private/r2-upload-list.txt: ${uploads.length} objects.`,
);
